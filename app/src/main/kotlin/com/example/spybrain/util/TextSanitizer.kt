package com.example.spybrain.util

/**
 * Утилита для очистки текста от специальных символов и маркдаун-разметки.
 * Используется для очистки AI-генерируемого текста от артефактов форматирования.
 */
object TextSanitizer {

    /**
     * Очищает текст от специальных символов и маркдаун-разметки.
     *
     * @param text Исходный текст для очистки.
     * @return Очищенный текст.
     */
    fun sanitize(text: String?): String {
        if (text.isNullOrBlank()) return ""

        return text
            // Удаляем маркдаун-разметку
            .replace(Regex("\\*+"), "") // Удаляем * жирного текста
            .replace(Regex("_+"), "") // Удаляем _ курсивного текста
            .replace(Regex("`+"), "") // Удаляем ` кода
            .replace(Regex("#+\\s*"), "") // Удаляем заголовки #
            .replace(Regex("\\[([^\\]]+)\\]\\([^\\)]+\\)"), "$1") // Заменяем ссылки [текст](url) на текст
            .replace(Regex("!\\[([^\\]]+)\\]\\([^\\)]+\\)"), "$1") // Заменяем изображения на alt-текст

            // Нормализуем тире и кавычки
            .replace(Regex("—"), "—") // Сохраняем длинное тире
            .replace(Regex("–"), "-") // Заменяем короткое тире на обычное
            .replace(Regex("[''\"\"]"), "\"") // Нормализуем кавычки

            // Удаляем лишние пробелы
            .replace(Regex("\\s+"), " ") // Схлопываем множественные пробелы
            .replace(Regex("^\\s+"), "") // Удаляем пробелы в начале
            .replace(Regex("\\s+$"), "") // Удаляем пробелы в конце

            // Удаляем другие специальные символы
            .replace(Regex("[<>]"), "") // Удаляем угловые скобки
            .replace(Regex("[|]"), "") // Удаляем вертикальные черты

            .trim()
    }

    /**
     * Проверяет, содержит ли текст маркдаун-разметку.
     *
     * @param text Текст для проверки.
     * @return true если текст содержит маркдаун-разметку.
     */
    fun containsMarkdown(text: String?): Boolean {
        if (text.isNullOrBlank()) return false

        return text.contains(Regex("\\*+|_+|`+|#+\\s*|\\[.+\\]\\(.+\\)|!\\[.+\\]\\(.+\\)"))
    }

    /**
     * Очищает текст только от лишних пробелов.
     *
     * @param text Исходный текст.
     * @return Текст с нормализованными пробелами.
     */
    fun normalizeWhitespace(text: String?): String {
        if (text.isNullOrBlank()) return ""

        return text
            .replace(Regex("\\s+"), " ")
            .replace(Regex("^\\s+"), "")
            .replace(Regex("\\s+$"), "")
            .trim()
    }
}